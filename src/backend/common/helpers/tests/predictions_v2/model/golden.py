"""Golden match stream for the HKF predictor tests.

``data/golden_stream.json.gz`` holds 2,773 PNW district matches from 2016 to 2025 in replay
order (the first two events of 2016-2022, all of 2023 and 2024, the first three events of
2025), each with its context, outcome and the expected prediction summary.

The expected values were first generated by an independent implementation of the same
model, so the test also checks this implementation against it. After an intended model
change, regenerate them from this implementation:

    PYTHONPATH=src python -m backend.common.helpers.tests.predictions_v2.model.golden
"""

import gzip
import json
import math
import os
from dataclasses import dataclass
from typing import Any, Dict, List, Optional

import numpy as np

from backend.common.consts.comp_level import CompLevel
from backend.common.consts.event_type import EventType
from backend.common.helpers.predictions_v2.model.predictor import HKFPredictor
from backend.common.helpers.predictions_v2.model.types import (
    MatchContext,
    MatchOutcome,
    MatchPrediction,
    RankingPointsPrediction,
    ScoreDistribution,
)
from backend.common.models.keys import Year

GOLDEN_PATH = os.path.join(os.path.dirname(__file__), "data", "golden_stream.json.gz")

Summary = Dict[str, Any]


@dataclass(frozen=True)
class GoldenMatch:
    year: Year
    context: MatchContext
    outcome: MatchOutcome
    expected: Summary


def _match(row: Dict[str, Any]) -> GoldenMatch:
    c, o = row["context"], row["outcome"]
    bd = o["score_breakdown"] or {}
    return GoldenMatch(
        year=c["year"],
        context=MatchContext(
            match_key=c["match_key"],
            event_key=c["event_key"],
            event_type=EventType(c["event_type"]),
            comp_level=CompLevel(c["comp_level"]),
            red_teams=tuple(c["red_teams"]),
            blue_teams=tuple(c["blue_teams"]),
        ),
        outcome=MatchOutcome(
            red_score=o["red_score"],
            blue_score=o["blue_score"],
            red_win=o["actual_red_win"],
            red_breakdown=bd.get("red"),
            blue_breakdown=bd.get("blue"),
            red_bonus_rps=o["red_bonus_rps"],
            blue_bonus_rps=o["blue_bonus_rps"],
            red_dqs=tuple(o["red_dqs"]),
            blue_dqs=tuple(o["blue_dqs"]),
        ),
        expected=row["prediction"],
    )


def load_golden() -> List[GoldenMatch]:
    with gzip.open(GOLDEN_PATH, "rt") as f:
        return [_match(row) for row in json.load(f)["matches"]]


def _score_summary(score: ScoreDistribution, actual: int) -> Summary:
    p = score.probs
    k = np.arange(len(p), dtype=float)
    mean = float(p @ k)
    sd = math.sqrt(max(float(p @ (k - mean) ** 2), 0.0))
    nz = p[p > 0]
    return {
        "mean": mean,
        "sd": sd,
        "skew": float(p @ (k - mean) ** 3) / max(sd, 1e-12) ** 3,
        "entropy": float(-(nz * np.log(nz)).sum()),
        "p_actual": score.prob(actual),
    }


def _rp_summary(rp: Optional[RankingPointsPrediction]) -> Optional[Summary]:
    if rp is None:
        return None
    return {
        "expected_rp": rp.expected_rp,
        "win_rp_prob": rp.win_rp_prob,
        "bonus_rp_probs": dict(rp.bonus_rp_probs),
        "median_rp": rp.median_rp,
        "max_rp": rp.max_rp,
    }


def summarize(pred: MatchPrediction, outcome: MatchOutcome) -> Summary:
    return {
        "red_win_prob": pred.red_win_prob,
        "red_score": _score_summary(pred.red_score, outcome.red_score),
        "blue_score": _score_summary(pred.blue_score, outcome.blue_score),
        "red_rp": _rp_summary(pred.red_rp),
        "blue_rp": _rp_summary(pred.blue_rp),
    }


def replay(model: HKFPredictor, matches: List[GoldenMatch]) -> List[Summary]:
    """Predict, then learn, every match in order. Starts a season at each year change."""
    out: List[Summary] = []
    for m in matches:
        if model.season != m.year:
            model.start_season(m.year)
        out.append(summarize(model.predict_match(m.context), m.outcome))
        model.update(m.context, m.outcome)
    return out


def regenerate() -> None:
    with gzip.open(GOLDEN_PATH, "rt") as f:
        data = json.load(f)
    summaries = replay(HKFPredictor(), load_golden())
    for row, summary in zip(data["matches"], summaries):
        row["prediction"] = summary
    data["generator"] = "backend.common.helpers.predictions_v2 (regenerated)"
    with gzip.open(GOLDEN_PATH, "wt") as f:
        json.dump(data, f, separators=(",", ":"))


if __name__ == "__main__":
    regenerate()
